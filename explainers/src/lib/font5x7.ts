export const glyph = (ch: string): string[] => G[ch.toUpperCase()] ?? G['?'];

/** Lit-dot coordinates (col,row) for lines of text centred in a cols x rows
 *  matrix of CHARACTER cells (each cell = 6x8 dots incl. 1-dot spacing). */
export const litDots = (
  lines: string[],
  charCols: number,
  charRows: number,
): Array<[number, number]> => {
  const out: Array<[number, number]> = [];
  const used = lines.slice(0, charRows);
  const rowOffset = Math.floor((charRows - used.length) / 2);
  used.forEach((line, li) => {
    const text = line.slice(0, charCols);
    const colOffset = Math.floor((charCols - text.length) / 2);
    [...text].forEach((ch, ci) => {
      const g = glyph(ch);
      for (let r = 0; r < GLYPH_H; r++) {
        for (let c = 0; c < GLYPH_W; c++) {
          if (g[r][c] === '1') {
            out.push([(colOffset + ci) * 6 + c, (rowOffset + li) * 8 + r]);
          }
        }
      }
    });
  });
  return out;
};
